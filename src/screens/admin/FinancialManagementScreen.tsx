const unwrap = (res: any): any => {
  if (res && typeof res === 'object' && 'data' in res) return res.data;
  return res;
};

const unwrapData = (res: any): any => {
  const u = unwrap(res);
  if (u && typeof u === 'object' && 'data' in u) return u.data;
  return u;
};

const asArray = <T,>(v: any): T[] => (Array.isArray(v) ? v : []);

const parseParents = (res: any): ParentRef[] => {
  const u = unwrapData(res);
  if (Array.isArray(u)) return u;
  if (Array.isArray(u?.parents)) return u.parents;
  return [];
};

const parseStudents = (res: any): StudentRef[] => {
  const u = unwrapData(res);
  if (Array.isArray(u)) return u;
  if (Array.isArray(u?.students)) return u.students;
  return [];
};

const parseStaff = (res: any): EmployeeRef[] => {
  const u = unwrapData(res);
  if (Array.isArray(u)) return u;
  if (Array.isArray(u?.teachers)) return u.teachers;
  if (Array.isArray(u?.employees)) return u.employees;
  return [];
};

const fmtMoney = (n?: number) =>
  `$${(Number.isFinite(n as number) ? (n as number) : 0).toFixed(2)}`;

const monthName = (m: number) =>
  new Date(2024, m - 1).toLocaleString('default', { month: 'short' });

const fullMonthName = (m: number) =>
  new Date(2024, m - 1).toLocaleString('default', { month: 'long' });

const initials = (name?: string) => {
  const s = (name || '').trim();
  if (!s) return '?';
  const parts = s.split(' ').filter(Boolean);
  if (parts.length >= 2) return (parts[0][0] + parts[1][0]).toUpperCase();
  return s.substring(0, 2).toUpperCase();
};

const statusStyle = (status: PaymentStatus) => {
  if (status === 'paid') return { bg: COLORS.primaryLight, text: COLORS.primary };
  if (status === 'partial') return { bg: COLORS.amberLight, text: COLORS.amber };
  return { bg: COLORS.redLight, text: COLORS.red };
};

const isBranchError = (err: any) => {
  const msg = err?.response?.data?.message || err?.message || '';
  return (
    typeof msg === 'string' && msg.toLowerCase().includes('branch id is required')
  );
};

